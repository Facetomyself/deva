await test('two personas instances and settings share an inode queue and reject stale edits', async t => {
  const dataDir = await sandbox(t)
  await writeJson(configPath(dataDir), { personas: { seeded: { general: true }, seededPrompt: { general: 'baseline' },
    order: ['legacy-only'], extra: { token: 'preserve' } }, skills: { roles: { essays: ['legacy-only'] } } })
  const first = await openPersonas({ dataDir })
  const second = await openPersonas({ dataDir })
  const settings = await openSettings({ dataDir })
  const one = await first.upsert({ name: 'Study', avatar: '{"shape":"auto"}' })
  const two = await second.upsert({ name: 'Reading' })
  await reject(second.upsert({ id: one.id, name: 'Missing revision' }), 'REVISION_REQUIRED')
  await reject(second.setEnabled(one.id, true), 'REVISION_REQUIRED')
  const snapshot = await first.list()
  const [enabledOne, enabledTwo, , sorted] = await Promise.all([
    first.setEnabled(one.id, true, one.revision), second.setEnabled(two.id, true, two.revision),
    settings.patch({ set: { theme: 'dark' } }), first.reorder([two.id, one.id, 'general'], snapshot.revision)
  ])
  assert.equal(enabledOne.enabled, true)
  assert.equal(enabledTwo.enabled, true)
  const disk = await readJson(configPath(dataDir))
  assert.deepEqual(disk.personas.enabled, { general: true, [one.id]: true, [two.id]: true })
  assert.deepEqual(disk.personas.order, [two.id, one.id, 'general', 'legacy-only'])
  assert.deepEqual(disk.personas.seededPrompt, { general: 'baseline' })
  assert.deepEqual(disk.personas.extra, { token: 'preserve' })
  assert.deepEqual(disk.skills, { roles: { essays: ['legacy-only'] } })
  assert.equal(disk.theme, 'dark')
  assert.deepEqual((await second.list()).order, sorted.order)
  await reject(second.upsert({ id: one.id, revision: one.revision, prompt: 'Stale' }), 'CONFLICT')
  await reject(second.reorder(snapshot.order, snapshot.revision), 'CONFLICT')
  const attempts = await Promise.allSettled([
    first.upsert({ id: one.id, revision: enabledOne.revision, name: 'Fresh A' }),
    second.upsert({ id: one.id, revision: enabledOne.revision, name: 'Stale B' })
  ])
  const winner = attempts.find(result => result.status === 'fulfilled')
  const stale = attempts.find(result => result.status === 'rejected')
  assert.equal(stale.reason.code, 'ERR_PERSONA_CONFLICT')
  assert.equal((await first.get(one.id)).name, winner.value.name)
})

await test('input IDs, accessors, byte limits, and client-assigned identities are rejected before writes', async t => {
  const dataDir = await sandbox(t)
  const personas = await openPersonas({ dataDir })
  const role = await personas.upsert({ name: '中文名字' })
  assert.match(role.id, /^persona-[a-f0-9]{32}$/u)
  for (const value of ['../escape', 'General', 'two..parts', 'trailing.', 'white space', 'a\n', 'constructor', 'toString',
    '__proto__', 'prototype', 'COM2.extra', 'NUL', 'a/b', 'a\\b', 'a'.repeat(65)]) {
    await reject(personas.get(value), 'INVALID')
  }
  for (const attack of [Object.create({ name: 'Inherited' }), JSON.parse('{"name":"Own","__proto__":{}}'),
    { get name() { assert.fail('accessor read') } }]) {
    await assert.rejects(personas.upsert(attack), { code: 'ERR_SETTINGS_INVALID' })
  }
  await reject(personas.upsert({ id: 'made-up', revision: role.revision, name: 'Other' }), 'NOT_FOUND')
  await reject(personas.upsert({ name: 'Name\nworkspace: /root' }), 'INVALID')
  await reject(personas.upsert({ name: '界'.repeat(90) }), 'INVALID')
  await reject(personas.upsert({ name: 'Huge prompt', prompt: '界'.repeat(22000) }), 'INVALID')
  await reject(personas.upsert({ name: 'Avatar proto', avatar: '{"colors":{"__proto__":"000"}}' }), 'INVALID')
  await reject(personas.upsert({ name: 'Model', model: 'provider: model' }), 'INVALID')
  await reject(personas.reorder(Array(2), (await personas.list()).revision), 'INVALID')
  assert.equal((await personas.list()).roles.length, 2)
})

await test('role links, corrupt UTF-8, malformed frontmatter and read-only targets stay unchanged', async t => {
  const base = await sandbox(t)
  const dataDir = join(base, 'home')
  const personas = await openPersonas({ dataDir, checkReferences: () => true })
  const role = await personas.upsert({ name: 'Safe owner' })
  const path = rolePath(dataDir, role.id)
  const outside = join(base, 'outside.md')
  const content = simple('Out of dir')
  await writeFile(outside, content)
  for (const alias of [link, symlink]) {
    assert.equal(resolve(path), path)
    await unlink(path)
    await alias(outside, path)
    await reject(personas.get(role.id), 'CORRUPT')
    await reject(personas.upsert({ id: role.id, revision: role.revision, name: 'Attempt' }), 'CORRUPT')
    await reject(personas.remove(role.id, role.revision), 'CORRUPT')
    assert.equal(await readFile(outside, 'utf8'), content)
  }
  await unlink(path)
  for (const bytes of [Buffer.from([0xff]), Buffer.from('---\nname: damaged\n'),
    Buffer.from('---\nname: one\nname: two\n---\n'), Buffer.from('---\nname: a\n__proto__: hidden\n---\n'),
    Buffer.from('---\nname: "broken\n---\n'), Buffer.from('---\nname: a\nextension:\n  constructor: hidden\n---\n'),
    Buffer.alloc(MAX_PERSONA_FILE_BYTES + 1, 0x61)]) {
    await writeFile(path, bytes)
    await reject(personas.upsert({ id: role.id, revision: role.revision, prompt: 'No overwrite' }), 'CORRUPT')
    assert.deepEqual(await readFile(path), bytes)
  }
  await writeFile(path, simple('Owner'))
  await chmod(path, 0o400)
  const readonly = await personas.get(role.id)
  await assert.rejects(personas.upsert({ id: role.id, revision: readonly.revision, name: 'No overwrite' }), { code: 'ERR_SETTINGS_READ_ONLY' })
  await assert.rejects(personas.remove(role.id, readonly.revision), { code: 'ERR_SETTINGS_READ_ONLY' })
  assert.equal(await readFile(path, 'utf8'), simple('Owner'))
})

