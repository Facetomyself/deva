await test('remove fails closed for missing hook and every known dependency; successful removal retires the identity', async t => {
  const dataDir = await sandbox(t)
  const closed = await openPersonas({ dataDir })
  const role = await closed.upsert({ name: 'Reader', enabled: true })
  await reject(closed.remove(role.id, role.revision), 'REFERENCED')
  const checked = []
  const personas = await openPersonas({ dataDir, checkReferences: id => { checked.push(id); return true } })
  const roster = await personas.list()
  await personas.reorder([role.id, 'general'], roster.revision)
  const config = await readJson(configPath(dataDir))
  await writeJson(configPath(dataDir), { ...config, mcp: { roles: { tool: [role.id.toUpperCase()] } } })
  await reject(personas.remove(role.id, role.revision), 'REFERENCED')
  await writeJson(configPath(dataDir), config)
  const tasks = join(dataDir, 'tasks.json')
  await writeJson(tasks, { version: 1, tasks: [{ auth: { personaId: role.id } }] })
  await reject(personas.remove(role.id, role.revision), 'REFERENCED')
  await writeFile(tasks, 'malformed task file')
  await reject(personas.remove(role.id, role.revision), 'REFERENCED')
  await writeJson(tasks, { version: 1, tasks: [] })
  const memory = join(dataDir, 'personas', 'memory')
  const memoryFile = join(memory, `${role.id}.json`)
  await mkdir(memory)
  await writeJson(memoryFile, { version: 2, personaId: role.id, entries: [{ title: 'A real reference' }] })
  await reject(personas.remove(role.id, role.revision), 'REFERENCED')
  await writeJson(memoryFile, { version: 2, personaId: role.id, entries: [] })
  const avatars = join(dataDir, 'personas', 'avatars')
  const avatar = join(avatars, `${role.id}.webp`)
  await mkdir(avatars)
  await writeFile(avatar, 'legacy data')
  await reject(personas.remove(role.id, role.revision), 'REFERENCED')
  assert.equal(resolve(avatar), avatar)
  await unlink(avatar)
  const clearedAvatar = join(avatars, role.id)
  await writeFile(clearedAvatar, '')
  assert.deepEqual(checked, [])
  const sessionsHeld = await openPersonas({ dataDir, checkReferences: () => false })
  await reject(sessionsHeld.remove(role.id, role.revision), 'REFERENCED')
  let calls = 0
  const changedBetweenChecks = await openPersonas({ dataDir, checkReferences: () => ++calls === 1 })
  await reject(changedBetweenChecks.remove(role.id, role.revision), 'REFERENCED')
  assert.deepEqual(await readJson(configPath(dataDir)), config)
  assert.equal((await personas.get(role.id)).revision, role.revision)
  assert.deepEqual(await personas.remove(role.id, role.revision), { ok: true })
  assert.deepEqual(checked, [role.id, role.id])
  assert.equal(await personas.get(role.id), null)
  const disk = await readJson(configPath(dataDir))
  assert.deepEqual(disk.personas.order, ['general'])
  assert.deepEqual(disk.personas.enabled, { general: true })
  assert.deepEqual(disk.personas.headlessRetiredIds, { [role.id]: true })
  assert.deepEqual(await readJson(memoryFile), { version: 2, personaId: role.id, entries: [] })
  assert.equal((await stat(clearedAvatar)).size, 0)
  await writeFile(rolePath(dataDir, role.id), simple('Stale restore'))
  assert.equal(await (await openPersonas({ dataDir })).get(role.id), null)
  assert.notEqual((await personas.upsert({ name: 'Reader' })).id, role.id)
})

await test('linked directories/config and config mutation failures never re-seed or clobber data', async t => {
  const base = await sandbox(t)
  const target = join(base, 'target')
  const home = join(base, 'home')
  const personasDir = join(home, 'personas')
  await mkdir(target)
  await mkdir(home)
  await symlink(target, personasDir)
  await reject(openPersonas({ dataDir: home }), 'CORRUPT')
  assert.equal(resolve(personasDir), personasDir)
  await unlink(personasDir)
  const cfg = configPath(home)
  const out = join(base, 'linked.json')
  await writeJson(out, { untouched: true })
  await link(out, cfg)
  await assert.rejects(openPersonas({ dataDir: home }), { code: 'ERR_SETTINGS_CORRUPT' })
  assert.deepEqual(await readJson(out), { untouched: true })
  assert.equal(resolve(cfg), cfg)
  await unlink(cfg)
  await writeJson(cfg, { personas: { enabled: {} } })
  const roster = await openPersonas({ dataDir: home })
  const role = await roster.upsert({ name: 'Kept' })
  await chmod(cfg, 0o400)
  await assert.rejects(roster.upsert({ id: role.id, revision: role.revision, name: 'Avoid partial write', enabled: true }),
    { code: 'ERR_SETTINGS_READ_ONLY' })
  assert.equal((await roster.get(role.id)).name, 'Kept')
  await unlink(cfg)
  await reject(roster.setEnabled(role.id, true, role.revision), 'CORRUPT')
})

