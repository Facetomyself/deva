  assert.equal(roster.roles[0].enabled, true)
  const { personas: stored } = await readJson(configPath(dataDir))
  assert.equal(stored.enabled.general, true)
  assert.equal(stored.seeded.general, true)
  assert.equal(roster.roles[0].workspaceId, '')
